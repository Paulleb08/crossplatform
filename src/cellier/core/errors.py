"""Erreurs métier. La CLI les affiche telles quelles, sans trace Python."""


class CellierError(Exception):
    """Base de toutes les erreurs attendues."""


class WineNotFound(CellierError): ...
class BottleExists(CellierError): ...
class BottleNotFound(CellierError): ...
class InvalidName(CellierError): ...
class InvalidSetting(CellierError): ...
class MissingComponent(CellierError): ...
class UnsupportedFile(CellierError): ...
class MountFailed(CellierError): ...
class CommandFailed(CellierError): ...
